import { writeFile } from 'node:fs/promises';
import { PROVINCES, districtsFor } from '../src/domain/disposal/regions.js';

const portal = 'https://www.data.go.kr';
const dataset = '15114146';
const perPage = 10_000;

async function download(path, parameters) {
  const url = new URL(path, portal);
  for (const [name, value] of parameters) url.searchParams.append(name, value);
  const response = await fetch(url, { signal: AbortSignal.timeout(45_000) });
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.json();
}

const { totalCount, tableVO } = await download('/download/columList.json', [['pk', dataset], ['ext', 'JSON']]);
if (!Number.isInteger(totalCount) || totalCount < 1 || !tableVO?.colNmList?.length) {
  throw new Error('공공데이터포털에서 수수료 자료의 목록을 받지 못했습니다.');
}
const pages = await Promise.all(Array.from({ length: Math.ceil(totalCount / perPage) }, (_, index) =>
  download('/download/standard.json', [
    ['publicDataPk', dataset], ['svcTableNm', tableVO.svcTableNm],
    ['totalCount', totalCount], ['perPage', perPage], ['page', index + 1],
    ...tableVO.colNmList.map(column => ['colNmList', column]),
  ])));
const rows = pages.flat();
if (rows.length !== totalCount) throw new Error(`수수료 자료 ${totalCount}행 중 ${rows.length}행을 받았습니다.`);

const collator = new Intl.Collator('ko', { numeric: true });
const regions = new Map();
const unmapped = new Set();
for (const row of rows) {
  let province = row.CTPV_NM?.trim();
  const district = province === '세종특별자치시' ? '' : row.SGG_NM?.trim().replace(/\s+/g, ' ');
  // Existing saved regions keep the app's labels after the administrative merger.
  if (province === '전남광주통합특별시') {
    province = districtsFor('광주광역시').includes(district) ? '광주광역시' : '전라남도';
  }
  if (!PROVINCES.includes(province) || (province !== '세종특별자치시' && !district)) {
    unmapped.add(`${province} ${district}`);
    continue;
  }
  const name = row.LAR_WAS_NM?.trim().replace(/\s+/g, ' ');
  const size = row.LAR_WAS_SPCFCT?.trim().replace(/\s+/g, ' ') || '';
  const fee = row.FEE?.trim();
  const date = row.CRTR_YMD?.trim();
  const validFee = row.PAID_FREE_YN === '무료' ? fee === '0' : row.PAID_FREE_YN === '유료' && /^[1-9]\d*$/.test(fee);
  if (!name || !/^\d{4}-\d{2}-\d{2}$/.test(date) || !validFee) {
    throw new Error(`수수료 확인이 필요한 원본 행: ${JSON.stringify(row)}`);
  }

  const key = [province, district].filter(Boolean).join(' ');
  if (!regions.has(key)) regions.set(key, { dates: new Set(), items: new Map() });
  const region = regions.get(key);
  region.dates.add(date);
  const itemKey = JSON.stringify([name, size]);
  const amount = Number(fee);
  if (!region.items.has(itemKey)) region.items.set(itemKey, [name, size, amount]);
  else if (region.items.get(itemKey)[2] !== amount) region.items.get(itemKey)[2] = null;
}
if (unmapped.size) throw new Error(`지역 매핑 확인 필요: ${[...unmapped].join(', ')}`);

const entries = [...regions.entries()].sort(([a], [b]) => collator.compare(a, b)).map(([region, { dates, items }]) => {
  const sortedDates = [...dates].sort();
  const period = [...new Set([sortedDates[0], sortedDates.at(-1)])];
  const sortedItems = [...items.values()].sort(([nameA, sizeA], [nameB, sizeB]) =>
    collator.compare(nameA, nameB) || collator.compare(sizeA, sizeB));
  return `  ${JSON.stringify(region)}: {\n    dates: ${JSON.stringify(period)},\n    rows: [\n${sortedItems.map(item => `      ${JSON.stringify(item)},`).join('\n')}\n    ],\n  },`;
});

const output = new URL('../src/domain/disposal/bulky-waste-fees.generated.js', import.meta.url);
await writeFile(output, `// Generated by scripts/update-bulky-waste-fees.js from data.go.kr dataset 15114146.\n// Rows contain [품목, 규격, 수수료]. null means the source lists conflicting amounts.\nexport default {\n${entries.join('\n')}\n};\n`);
console.log(`${totalCount}개 원본 행에서 ${regions.size}개 지역의 수수료 자료를 생성했습니다.`);
